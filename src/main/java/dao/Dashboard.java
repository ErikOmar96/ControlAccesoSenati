    public static void mostrarJPanel(JPanel panel) {
        panel.setSize(750, 430);
        panel.setLocation(0,0);
        
        content.removeAll();
        content.add(panel, BorderLayout.CENTER);
        content.revalidate();
        content.repaint();
    }
    
